// Generates dynamic ranked leaderboard including current user
export function getComputedLeaderboard(
  scope: "class" | "school" | "country" | "league",
  sortBy: "xp" | "coins",
  currentUserStats: { xp: number; coins: number; streak: number; level: number }
): { list: LeaderboardUser[]; currentUser: LeaderboardUser; leaderGap: number; nextRankGap: number } {
  const peers = baseLeaderboardPeers[scope] || baseLeaderboardPeers.class;

  const currentUserItem: Omit<LeaderboardUser, "rank"> = {
    id: "current_user",
    name: "Сіз (Сіздің профиль)",
    avatar: "⭐",
    city: "Алматы",
    school: "9 «А» сынып",
    grade: 9,
    xp: currentUserStats.xp,
    coins: currentUserStats.coins,
    streak: currentUserStats.streak,
    tasksSolved: Math.max(18, Math.floor(currentUserStats.xp / 45)),
    change: 1,
    badge: `LVL ${currentUserStats.level} Чемпион`,
    isCurrentUser: true,
  };

  const combined = [...peers, currentUserItem];

  // Sort by selected metric: XP or Newton Coins (NC)
  combined.sort((a, b) => {
    if (sortBy === "xp") {
      return b.xp - a.xp;
    } else {
      return b.coins - a.coins;
    }
  });

  // Assign 1-indexed ranks
  const rankedList: LeaderboardUser[] = combined.map((item, index) => ({
    ...item,
    rank: index + 1,
  }));

  const userInRank = rankedList.find((u) => u.isCurrentUser) || rankedList[0];

  // Distance to rank 1
  const leader = rankedList[0];
  const leaderMetric = sortBy === "xp" ? leader.xp : leader.coins;
  const userMetric = sortBy === "xp" ? userInRank.xp : userInRank.coins;
  const leaderGap = Math.max(0, leaderMetric - userMetric);

  // Distance to the user right above in the ranking
  const prevUser = userInRank.rank > 1 ? rankedList[userInRank.rank - 2] : null;
  const prevMetric = prevUser ? (sortBy === "xp" ? prevUser.xp : prevUser.coins) : userMetric;
  const nextRankGap = prevUser ? Math.max(0, prevMetric - userMetric) : 0;

  return {
    list: rankedList,
    currentUser: userInRank,
    leaderGap,
    nextRankGap,
  };
}
